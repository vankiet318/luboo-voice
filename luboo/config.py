LOCAL_STT_MODEL = "small"                    # "base" is faster, "small" is better for Vietnamese

# ---------- Wake word ----------
# Luboo only listens and speaks in English.
# Custom-trained models live in resources/wakewords/ (see docs/GUIDE.md). When all files exist, the app uses them;
# otherwise it falls back to openWakeWord's bundled model (CC BY-NC-SA 4.0 — non-commercial).
WAKEWORDS_DIR = os.path.join(RESOURCES_DIR, "wakewords")
CUSTOM_WAKE_WORDS = {"hey_luboo": "en"}
FALLBACK_WAKE_WORDS = {"hey_jarvis_v0.1": "en"}
WAKE_LABELS = {"hey_luboo": "Hey Luboo", "hey_jarvis_v0.1": "Hey Jarvis"}
USE_CUSTOM_WAKE_WORDS = all(os.path.exists(os.path.join(WAKEWORDS_DIR, f"{n}.onnx"))
                            for n in CUSTOM_WAKE_WORDS)
WAKE_WORDS = CUSTOM_WAKE_WORDS if USE_CUSTOM_WAKE_WORDS else FALLBACK_WAKE_WORDS
# Only trigger when the score is >= threshold for WAKE_PATIENCE consecutive 80ms frames (false triggers usually
# "flash" for just 1 frame).
# Custom model (2nd training run): 0.99 + 3 frames -> ~1–2 false triggers/hour, catches ~95% of calls.
WAKE_THRESHOLD = 0.99 if USE_CUSTOM_WAKE_WORDS else 0.5
WAKE_PATIENCE = 3 if USE_CUSTOM_WAKE_WORDS else 1


def wake_word_path(name: str) -> str:
    return os.path.join(WAKEWORDS_DIR if name in CUSTOM_WAKE_WORDS else MODELS_DIR, f"{name}.onnx")


# ---------- Recording ----------
SAMPLE_RATE = 16000
FRAME = 1280                 # 80ms per frame (wake word model)
# How long a silence counts as end of speech (Silero VAD; the old loudness-based check needed 1.0s).
# Measured with tools/bench_vad.py:
# 0.6s -> cut off early on 5/30 sentences with a 0.45s mid-sentence pause; 0.7s -> 1/30 (end reported after ~0.75s).
SILENCE_SEC = 0.7
FIRST_WAIT_SEC = 6           # after the wake word, max time to wait for you to start speaking
FOLLOWUP_SEC = 6             # after the bot replies, how long to keep listening (no need to call it again)
MAX_RECORD_SEC = 20
MIN_UTTERANCE_SEC = 0.4      # shorter utterances -> treated as noise, ignored
# Silero VAD (resources/models/silero_vad.onnx)
VAD_THRESHOLD = 0.5          # speech probability needed to count as "speaking"
VAD_MIN_SPEECH_SEC = 0.15    # continuous speech needed to count as speech start (ignores "clicks")
VAD_PRE_ROLL_SEC = 0.3       # keep extra audio before the VAD start point (so the first sound isn't lost)
MIC_BUFFER_SEC = 2.0         # the mic always keeps the last ~2s

# ---------- Interruption (barge-in) and utterance merging ----------
# Only active once a voice is enrolled (Settings -> Voice ID): only the owner's voice can interrupt Luboo.
BARGE_IN = True
BARGE_DUCK_GAIN = 0.3        # as soon as a human voice is heard -> duck Luboo down to this level (immediately)
BARGE_VERIFY_SEC = 0.8       # hear this many seconds of speech before checking whether it's the owner
BARGE_VERIFY_MAX_SEC = 1.5   # score still borderline (>= SPEAKER_GRAY) -> keep listening up to this, then re-check
SPEAKER_GRAY = 0.25
BARGE_MIN_SPEECH_SEC = 0.3   # shorter sounds (coughs, "umm") -> not counted as an interruption
# You pause mid-sentence and continue while Luboo is still thinking (hasn't spoken yet) -> merge into one utterance
MERGE_WINDOW_SEC = 3.0       # only merge if you continue within this many seconds after pausing
# Similarity to the owner's voice (cosine, WeSpeaker) to count as "really you". Tested with 8 TTS voices (10/2026):
# 0.8s clip -> owner accepted 92%, others falsely accepted 0.3%; 1.5s clip -> 100% / 0.6%. Retune with a real voice.
SPEAKER_THRESHOLD = 0.45
