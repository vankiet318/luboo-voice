ICON_PATH = os.path.join(RESOURCES_DIR, "icon.ico")       # generated by packaging/make_icon.py
# Where user settings are stored (the app install folder is read-only)
DATA_DIR = os.path.join(os.environ.get("APPDATA", os.path.expanduser("~")), APP_NAME)

# ---------- Groq ----------
STT_MODEL = "whisper-large-v3-turbo"
# (Groq retired Llama 3.x and groq/compound on the free tier in 08–09/2026 — see console.groq.com/docs/deprecations)
SEARCH_MODEL = "openai/gpt-oss-120b"         # knowledge questions: enables the browser_search web tool
CHAT_MODEL = "openai/gpt-oss-120b"           # regular chat
FALLBACK_MODEL = "openai/gpt-oss-20b"        # fallback when rate-limited — faster, less smart
