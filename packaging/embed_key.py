"""Generate luboo/_embedded_key.py containing the (obfuscated) Groq API key for builds sent to friends for testing.

Only used via `packaging/build.ps1 -EmbedKey`. The key comes from the LUBOO_EMBED_KEY env var (set by build.ps1).
OBFUSCATION ≠ ENCRYPTION: anyone technical can still extract the key from the exe — only send it to trusted people;
if the key leaks, revoke it at console.groq.com/keys and rebuild.
"""
import os
import secrets
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "luboo", "_embedded_key.py")

key = os.environ.get("LUBOO_EMBED_KEY", "").strip()
if not key.startswith("gsk_"):
    sys.exit("No valid Groq API key found (must start with gsk_).")
data = key.encode()
pad = secrets.token_bytes(len(data))
with open(OUT, "w", encoding="utf-8") as f:
    f.write('"""AUTO-GENERATED by packaging/embed_key.py — do NOT commit (already in .gitignore)."""\n')
    f.write(f'_PAD = bytes.fromhex("{pad.hex()}")\n')
    f.write(f'_DATA = bytes.fromhex("{bytes(a ^ b for a, b in zip(data, pad)).hex()}")\n\n\n')
    f.write("def load() -> str:\n    return bytes(a ^ b for a, b in zip(_DATA, _PAD)).decode()\n")
print(f"Embedded key ({key[:4]}…{len(key)} chars) into luboo/_embedded_key.py")
